-- DataScope metadata schema; business schemas are independent.
CREATE TABLE ACTION_DEFINITION(NAME_ TEXT PRIMARY KEY,TITLE_ TEXT NOT NULL,DESCRIPTION_ TEXT NOT NULL,CONFIRM_ INTEGER NOT NULL,PARAMETER_JSON_ TEXT NOT NULL,SCRIPT_ TEXT NOT NULL);


CREATE TABLE BUSINESS_ACCOUNT(ID_ INTEGER PRIMARY KEY,DATABASE_ID_ TEXT NOT NULL,USERNAME_ TEXT NOT NULL,NAME_ TEXT NOT NULL,BUSINESS_USER_ID_ INTEGER NOT NULL CHECK(BUSINESS_USER_ID_>0),PASSWORD_HASH_ TEXT NOT NULL,PERMISSIONS_ TEXT NOT NULL,ACTIVE_ INTEGER NOT NULL DEFAULT 1,AUTH_VERSION_ INTEGER NOT NULL DEFAULT 1,UNIQUE(DATABASE_ID_,USERNAME_));

CREATE TABLE CONFIG_RECORD(BUCKET_ TEXT NOT NULL,KEY_ TEXT NOT NULL,DATA_ TEXT NOT NULL,PRIMARY KEY(BUCKET_,KEY_));

CREATE TABLE CONFIG_VERSION(BUCKET_ TEXT NOT NULL,KEY_ TEXT NOT NULL,REVISION_ INTEGER NOT NULL,DATA_ TEXT NOT NULL,CREATED_AT_ TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(BUCKET_,KEY_,REVISION_));

CREATE TABLE CONNECTION_CONFIG(PURPOSE_ TEXT PRIMARY KEY CHECK(PURPOSE_ IN('READ','WRITE')),CONFIG_JSON_ TEXT NOT NULL DEFAULT '{}',PASSWORD_CIPHERTEXT_ BLOB);

CREATE TABLE KNOWLEDGE(KEY_ TEXT PRIMARY KEY,DATA_ TEXT NOT NULL);

CREATE VIRTUAL TABLE KNOWLEDGE_SEARCH USING fts5(KEY_ UNINDEXED,NAME_,DESCRIPTION_,CONTENT_,tokenize='trigram');

CREATE TABLE PLATFORM_GRANT(USER_ID_ INTEGER NOT NULL,DATABASE_ID_ TEXT NOT NULL,PERMISSIONS_ TEXT NOT NULL,BUSINESS_USER_ID_ INTEGER NOT NULL DEFAULT 0,PRIMARY KEY(USER_ID_,DATABASE_ID_));

CREATE TABLE QUERY_FRAGMENT(NAME_ TEXT PRIMARY KEY,SQL_ TEXT NOT NULL);

CREATE TABLE QUERY_POLICY(TABLE_NAME_ TEXT PRIMARY KEY,SQL_ TEXT NOT NULL,DATA_ TEXT NOT NULL);

CREATE TABLE QUERY_TOOL(NAME_ TEXT PRIMARY KEY,DESCRIPTION_ TEXT NOT NULL,SQL_ TEXT NOT NULL,PARAMETER_JSON_ TEXT NOT NULL);

CREATE TABLE SCHEMA_VERSION(VERSION_ INTEGER PRIMARY KEY,APPLIED_AT_ TEXT NOT NULL);

CREATE TABLE SOURCE_CONFIG(ID_ TEXT PRIMARY KEY,DATA_ TEXT NOT NULL);


CREATE TRIGGER TR_KNOWLEDGE_INSERT AFTER INSERT ON KNOWLEDGE BEGIN INSERT INTO KNOWLEDGE_SEARCH VALUES(new.KEY_,json_extract(new.DATA_,'$.name'),coalesce(json_extract(new.DATA_,'$.description'),json_extract(new.DATA_,'$.summary'),''),json_extract(new.DATA_,'$.content'));END;

CREATE TRIGGER TR_KNOWLEDGE_UPDATE AFTER UPDATE ON KNOWLEDGE BEGIN DELETE FROM KNOWLEDGE_SEARCH WHERE KEY_=old.KEY_;INSERT INTO KNOWLEDGE_SEARCH VALUES(new.KEY_,json_extract(new.DATA_,'$.name'),coalesce(json_extract(new.DATA_,'$.description'),json_extract(new.DATA_,'$.summary'),''),json_extract(new.DATA_,'$.content'));END;

CREATE TRIGGER TR_KNOWLEDGE_DELETE AFTER DELETE ON KNOWLEDGE BEGIN DELETE FROM KNOWLEDGE_SEARCH WHERE KEY_=old.KEY_;END;
